const datePattern = /^\d{4}-\d{2}-\d{2}$/;
const slugPattern = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const hiddenUnicode = /[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F\u00AD\u200B-\u200F\u202A-\u202E\u2060\u2066-\u2069\uFEFF]/;
const artifactPattern = /(?:^|\s)(?:TODO|FIXME|вставьте сюда|служебная инструкция|сгенерированный ответ|как ии)(?:\s|$)/i;
const htmlPattern = /<\/?[a-z][^>]*>/i;

const textValues = (value) => {
  if (typeof value === "string") return [value];
  if (Array.isArray(value)) return value.flatMap(textValues);
  if (value && typeof value === "object") return Object.values(value).flatMap(textValues);
  return [];
};

export const validateEditorialData = () => {
  const errors = [];
  const unique = new Set();

  for (const article of articles) {
    if (!slugPattern.test(article.slug)) errors.push(`Статья ${article.id}: некорректный slug`);
    if (unique.has(`article:${article.slug}`)) errors.push(`Повторный slug статьи: ${article.slug}`);
    unique.add(`article:${article.slug}`);
    for (const field of ["publishedAt", "modifiedAt", "legalReviewedAt"]) {
      if (!datePattern.test(article[field] || "")) errors.push(`Статья ${article.slug}: некорректная дата ${field}`);
    }
    if (!article.title || !article.description || !article.shortAnswer || !article.sections?.length) errors.push(`Статья ${article.slug}: не заполнены обязательные поля`);
    if (!article.sources?.length) errors.push(`Статья ${article.slug}: отсутствуют официальные источники`);
    for (const source of article.sources || []) {
      if (!source.title || !/^https:\/\//.test(source.url || "")) errors.push(`Статья ${article.slug}: некорректный источник`);
    }
    for (const value of textValues(article)) {
      if (hiddenUnicode.test(value)) errors.push(`Статья ${article.slug}: найден скрытый Unicode`);
      if (artifactPattern.test(value)) errors.push(`Статья ${article.slug}: найден служебный артефакт`);
      if (htmlPattern.test(value)) errors.push(`Статья ${article.slug}: HTML запрещён в данных`);
    }
  }

  for (const item of practiceCases) {
    if (!slugPattern.test(item.slug)) errors.push(`Кейс ${item.id}: некорректный slug`);
    if (unique.has(`case:${item.slug}`)) errors.push(`Повторный slug кейса: ${item.slug}`);
    unique.add(`case:${item.slug}`);
    for (const field of ["publishedAt", "modifiedAt"]) {
      if (!datePattern.test(item[field] || "")) errors.push(`Кейс ${item.slug}: некорректная дата ${field}`);
    }
    for (const field of ["title", "situation", "materials", "work", "next", "description"]) {
      if (!item[field]) errors.push(`Кейс ${item.slug}: отсутствует поле ${field}`);
    }
    for (const value of textValues(item)) {
      if (hiddenUnicode.test(value)) errors.push(`Кейс ${item.slug}: найден скрытый Unicode`);
      if (artifactPattern.test(value)) errors.push(`Кейс ${item.slug}: найден служебный артефакт`);
      if (htmlPattern.test(value)) errors.push(`Кейс ${item.slug}: HTML запрещён в данных`);
    }
  }

  if (errors.length) throw new Error(`Редакционные данные не прошли проверку:\n- ${errors.join("\n- ")}`);
  return true;
};

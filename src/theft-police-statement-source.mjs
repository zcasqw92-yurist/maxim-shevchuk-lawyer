const htmlPattern = /<\/?[a-z][^>]*>/i;
const textValues = (value) => typeof value === "string" ? [value] : Array.isArray(value) ? value.flatMap(textValues) : value && typeof value === "object" ? Object.values(value).flatMap(textValues) : [];

export const validateTheftPoliceStatementData = () => {
  const errors = [];
  const unique = new Set();
  for (const article of theftPoliceStatementArticles) {
    if (!slugPattern.test(article.slug)) errors.push(`Статья ${article.id}: некорректный slug`);
    if (unique.has(article.slug)) errors.push(`Повторный slug статьи: ${article.slug}`);
    unique.add(article.slug);
    for (const field of ["publishedAt", "modifiedAt", "legalReviewedAt"]) if (!datePattern.test(article[field] || "")) errors.push(`Статья ${article.slug}: некорректная дата ${field}`);
    if (!article.title || !article.description || !article.shortAnswer || !article.sections?.length) errors.push(`Статья ${article.slug}: не заполнены обязательные поля`);
    if (!article.serviceSlug || !article.serviceLabel || !article.ctaTitle) errors.push(`Статья ${article.slug}: не заполнена связанная услуга или CTA`);
    if (!article.sources?.length) errors.push(`Статья ${article.slug}: отсутствуют официальные источники`);
    if (!article.finalSection?.id || !article.finalSection?.groups?.length || !article.inlineFinalCta) errors.push(`Статья ${article.slug}: не настроен финальный конверсионный блок`);
    if (article.listPolicyVersion !== 1) errors.push(`Статья ${article.slug}: не включена утверждённая система смысловых маркеров`);
    const mistakes = article.sections?.find((section) => section.id === "mistakes-before-filing");
    if (!mistakes?.avoid?.length || mistakes.avoid.length < 4) errors.push(`Статья ${article.slug}: нет явного блока ошибок с крестиками`);
    const property = article.sections?.find((section) => section.id === "describe-property");
    if (!property?.bullets?.length) errors.push(`Статья ${article.slug}: нейтральные примеры имущества не отделены от положительных действий`);
    const softCtas = article.sections?.flatMap((section) => section.microCta ? [section.microCta] : []) || [];
    if (!softCtas.length || softCtas.some((cta) => cta.href !== `#${article.finalSection.id}`)) errors.push(`Статья ${article.slug}: промежуточный CTA должен вести только к финальному блоку`);
    if (article.finalSection.groups.some((group) => group.kind !== "check")) errors.push(`Статья ${article.slug}: финальные списки должны быть положительными действиями`);
    for (const source of article.sources || []) if (!source.title || !/^https:\/\//.test(source.url || "")) errors.push(`Статья ${article.slug}: некорректный источник`);
    for (const value of textValues(article)) {
      if (hiddenUnicode.test(value)) errors.push(`Статья ${article.slug}: найден скрытый Unicode`);
      if (artifactPattern.test(value)) errors.push(`Статья ${article.slug}: найден служебный артефакт`);
      if (htmlPattern.test(value)) errors.push(`Статья ${article.slug}: HTML запрещён в данных`);
    }
  }
  if (errors.length) throw new Error(`Данные статьи о краже не прошли проверку:\n- ${errors.join("\n- ")}`);
  return true;
};
